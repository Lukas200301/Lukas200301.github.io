#!/usr/bin/env python3
"""Build js/search-index.js: the text inside every tool, game and project page, for the Ctrl+K palette.

Run from the repository root after adding or changing a page:
    python3 scripts/build-search-index.py

It collects headings, panel titles, labels, buttons, table headers, select options, chips, short hints and the
page description from each page's HTML, adds the extra phrases from scripts/search-keywords.json, removes
duplicates and writes window.SEARCH_INDEX. No dependencies beyond the Python standard library.
"""
import glob, json, os, re
from html.parser import HTMLParser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = sorted(glob.glob(os.path.join(ROOT, 'tools', '*', 'index.html')) + glob.glob(os.path.join(ROOT, 'games', '*', 'index.html'))
               + glob.glob(os.path.join(ROOT, 'projects', '*', 'index.html')) + [os.path.join(ROOT, 'stats', 'index.html')])

# elements whose text is a useful search phrase
TAGS = {'h1', 'h2', 'h3', 'h4', 'label', 'button', 'th', 'dt', 'option', 'legend', 'summary', 'figcaption', 'li', 'kbd'}
CLASS_HINTS = ('panel__title', 'meta-item', 'chip', 'hint', 'stat', 'tab', 'kv', 'card__title', 'section-title', 'feature', 'label', 'seg')
SKIP = {'script', 'style', 'noscript', 'svg', 'head', 'template'}


class Grab(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []      # (tag, wanted)
        self.skip = 0
        self.buf = []        # open text buffers for wanted elements
        self.out = []
        self.desc = ''
        self.title = ''
        self.in_title = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == 'meta' and a.get('name') == 'description':
            self.desc = a.get('content', '')
        if tag == 'title':
            self.in_title = True
        if tag in SKIP:
            self.skip += 1
        if tag in ('br', 'img', 'input', 'meta', 'link', 'hr', 'source', 'col', 'area', 'base', 'wbr'):
            if tag == 'input' and a.get('placeholder'):
                self.out.append(a['placeholder'])
            return
        cls = a.get('class', '') or ''
        wanted = (tag in TAGS or any(h in cls for h in CLASS_HINTS) or a.get('title')) and not self.skip
        if a.get('title') and not self.skip:
            self.out.append(a['title'])
        if a.get('aria-label') and not self.skip and tag in ('button', 'section', 'nav'):
            self.out.append(a['aria-label'])
        self.stack.append((tag, bool(wanted)))
        if wanted:
            self.buf.append([])

    def handle_endtag(self, tag):
        if tag == 'title':
            self.in_title = False
        if tag in SKIP and self.skip:
            self.skip -= 1
        # close up to the matching tag (HTML is forgiving)
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i][0] == tag:
                for t, w in reversed(self.stack[i:]):
                    if w and self.buf:
                        self.out.append(' '.join(self.buf.pop()))
                del self.stack[i:]
                break

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        if self.skip:
            return
        t = data.strip()
        if t:
            for b in self.buf:
                b.append(t)


def clean(s):
    s = re.sub(r'\s+', ' ', s).strip(' ·:–-|*').strip()
    if s.count('(') > s.count(')'):            # "Jitter (σ" → "Jitter"
        s = s[:s.rfind('(')].strip()
    if s.startswith('(') and s.endswith(')'):
        s = s[1:-1].strip()
    return s


def main():
    extra = json.load(open(os.path.join(ROOT, 'scripts', 'search-keywords.json'), encoding='utf-8'))
    pages = []
    for f in PAGES:
        if not os.path.exists(f):
            continue
        rel = os.path.relpath(os.path.dirname(f), ROOT).replace(os.sep, '/') + '/'
        html = open(f, encoding='utf-8').read()
        if re.search(r'<meta\s+http-equiv="refresh"', html, re.I):     # redirect stub for a moved page
            continue
        g = Grab()
        g.feed(html)
        title = clean(g.title.split('|')[0])
        phrases, seen = [], set()
        for s in [*extra.get(rel, []), *g.out, *re.split(r'(?<=[.!?])\s+', g.desc)]:
            s = clean(s)
            k = s.lower()
            if not (3 <= len(s) <= 90) or k in seen or k == title.lower() or not re.search(r'[a-zA-Z]', s):
                continue
            if re.fullmatch(r'[\d\s.,:/%x×+-]+', s):     # numbers only
                continue
            seen.add(k)
            phrases.append(s)
        pages.append({'h': rel, 't': title, 'p': phrases[:160]})
    out = ('/* Generated by scripts/build-search-index.py: the text inside every tool, game and project page,\n'
           '   searched by the Ctrl+K palette ("Found inside"). Do not edit by hand; run the script again. */\n'
           'window.SEARCH_INDEX = ' + json.dumps({'v': 1, 'pages': pages}, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open(os.path.join(ROOT, 'js', 'search-index.js'), 'w', encoding='utf-8').write(out)
    print(f'{len(pages)} pages, {sum(len(p["p"]) for p in pages)} phrases, {len(out) // 1024} KB')


if __name__ == '__main__':
    main()
